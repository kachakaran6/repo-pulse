import type { Repository, RepoStatus, CommitDay, SummaryStats } from '../types.js';

function generate90DayActivity(pattern: RepoStatus, seedOffset = 0): CommitDay[] {
  const result: CommitDay[] = [];
  const now = new Date();

  for (let i = 89; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 86400000);
    const dayStr = d.toISOString().split('T')[0];
    let commits = 0;

    if (pattern === 'active') {
      if ((i + seedOffset) % 2 === 0 || i < 5) {
        commits = ((i + seedOffset) % 4) + 1;
      }
    } else if (pattern === 'cooling') {
      if (i > 8 && i < 45 && (i + seedOffset) % 3 === 0) {
        commits = ((i + seedOffset) % 3) + 1;
      }
    } else if (pattern === 'stale') {
      if (i > 28 && i < 70 && (i + seedOffset) % 6 === 0) {
        commits = 1;
      }
    } else if (pattern === 'dead') {
      if (i > 75 && (i + seedOffset) % 10 === 0) {
        commits = 1;
      }
    }

    result.push({
      day: dayStr,
      commits,
      commits_mine: commits,
      commits_all: commits,
    });
  }

  return result;
}

