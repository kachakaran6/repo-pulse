  const staleCount = repos.filter((r) => r.status === 'stale' && !r.is_retired).length;
  const deadCount = repos.filter((r) => r.status === 'dead' && !r.is_retired).length;
  const retiredCount = repos.filter((r) => r.is_retired).length;
